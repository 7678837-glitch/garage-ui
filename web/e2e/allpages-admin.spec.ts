import { mkdirSync, appendFileSync } from 'node:fs';
import { assertAuthenticated, openNavigation, openAccount, openDisclosure } from './interactions';
const dir = process.env.ALLPAGES_EVIDENCE ?? '/tmp/garage-ui-allpages-admin';
const admin = administrator.username, password = administrator.password;
async function login(page: Page, user = admin, pass = password) { await page.goto('/'); await page.getByLabel('Username', { exact: true }).fill(user); await page.getByLabel('Password', { exact: true }).fill(pass); await page.getByRole('button', { name: 'Log in', exact: true }).click(); await assertAuthenticated(page); }
async function nav(page: Page, name: string) { await openNavigation(page); await page.getByRole('navigation', { name: 'Sections' }).getByRole('link', { name, exact: true }).click(); }
async function shot(page: Page, name: string, width: number) {
    mkdirSync(dir, { recursive: true });
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: `${dir}/${name}-${width}.png`, fullPage: true });
    const geometry = await page.evaluate(() => { const visible = (e: Element) => { const r = e.getBoundingClientRect(); return e.checkVisibility() && r.width > 0 && r.height > 0; }; const rect = (e: Element) => { const r = e.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; }; return { scrollWidth: document.documentElement.scrollWidth, viewport: innerWidth, headings: Array.from(document.querySelectorAll('h1,h2,h3')).filter(visible).map(e => ({ text: e.textContent, ...rect(e) })), header: Array.from(document.querySelectorAll('header')).filter(visible).map(rect), fields: Array.from(document.querySelectorAll('input:not([type=password]),input[type=password],select,button,summary')).filter(visible).map(e => ({ kind: e.tagName, type: e.getAttribute('type'), label: e.getAttribute('aria-label') || e.closest('label')?.textContent || e.textContent, ...rect(e), fontSize: getComputedStyle(e).fontSize })) }; });
    appendFileSync(`${dir}/geometry.jsonl`, JSON.stringify({ page: name, width, ...geometry }) + '\n');
    expect.soft(geometry.scrollWidth, `${name} document overflow`).toBeLessThanOrEqual(width);
}
function record(name: string, width: number, actions: string[]) { appendFileSync(`${dir}/actions.jsonl`, JSON.stringify({ page: name, width, result: 'passed', actions }) + '\n'); }
